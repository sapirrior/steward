const THEME_MAP: Record<ThemeName, Theme> = {
  dark: darkTheme,
  light: lightTheme,
  'dark-daltonized': darkDaltonizedTheme,
  'light-daltonized': lightDaltonizedTheme,
  'dark-ansi': darkAnsiTheme,
  'light-ansi': lightAnsiTheme,
};

export function getTheme(name?: string | null): Theme {
  const key = (name || '').trim().toLowerCase() as ThemeName;
  return THEME_MAP[key] ?? darkTheme;
}
